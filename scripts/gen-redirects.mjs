/*
 * Generates redirects from the old Hexo URLs to the new Astro URLs.
 *
 * Old permalink pattern (Hexo `:year/:month/:day/:title/`, date taken in UTC):
 *   /2026/09/10/Fake Gravity/   ->   /posts/fake-gravity/
 *
 * Writes:
 *   - src/data/redirects.mjs   (imported by astro.config.mjs, host-agnostic)
 *   - public/_redirects        (301 rules for Cloudflare Pages / Netlify, URL-encoded)
 *
 * Re-run it after `scripts/migrate-hexo.mjs`:
 *   node scripts/gen-redirects.mjs && pnpm build
 */

import fs from "node:fs";
import path from "node:path";

const projectRoot = path.resolve(import.meta.dirname, "..");
const postsDir = path.join(projectRoot, "src/content/posts");

/** Mirrors the slug Astro generates for a content entry: lowercase, whitespace -> dash. */
function slugify(name) {
	return name.trim().toLowerCase().replace(/\s+/g, "-");
}

/** "2026-09-11T00:23:07+08:00" -> [2026, 09, 10] (UTC), matching Hexo's permalink behaviour. */
function utcDateParts(published) {
	const iso = String(published).trim().replace(" ", "T");
	const withZone = /[+-]\d{2}:\d{2}$|Z$/.test(iso) ? iso : `${iso}+08:00`;
	const d = new Date(withZone);
	return [
		String(d.getUTCFullYear()),
		String(d.getUTCMonth() + 1).padStart(2, "0"),
		String(d.getUTCDate()).padStart(2, "0"),
	];
}

function readPublished(file) {
	const raw = fs.readFileSync(file, "utf8");
	const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
	if (!match) return null;
	const line = match[1].match(/^published:\s*(.+)$/m);
	return line ? line[1].replace(/^["']|["']$/g, "") : null;
}

const redirects = {};
const lines = [];
const missing = [];

for (const entry of fs.readdirSync(postsDir, { withFileTypes: true }).sort((a, b) =>
	a.name.localeCompare(b.name),
)) {
	let name;
	let file;

	if (entry.isDirectory()) {
		file = path.join(postsDir, entry.name, "index.md");
		if (!fs.existsSync(file)) continue;
		name = entry.name;
	} else if (entry.name.endsWith(".md")) {
		file = path.join(postsDir, entry.name);
		name = entry.name.replace(/\.md$/, "");
	} else {
		continue;
	}

	const published = readPublished(file);
	if (!published) {
		missing.push(name);
		continue;
	}

	const [year, month, day] = utcDateParts(published);
	const slug = slugify(name);
	const from = `/${year}/${month}/${day}/${name}/`;
	const to = `/posts/${slug}/`;

	redirects[from] = to;
	lines.push(`${encodeURI(from)} ${encodeURI(to)} 301`);
}

// Pages that existed on the Hexo site but have no 1:1 counterpart in Fuwari.
const pageRedirects = {
	"/archives/": "/archive/",
	"/categories/": "/archive/",
	"/tags/": "/archive/",
	"/links/": "/",
	"/search/": "/archive/",
	"/page/2/": "/2/",
};
for (const [from, to] of Object.entries(pageRedirects)) {
	redirects[from] = to;
	lines.push(`${encodeURI(from)} ${encodeURI(to)} 301`);
}

const dataDir = path.join(projectRoot, "src/data");
fs.mkdirSync(dataDir, { recursive: true });

// Emit the object by hand so the output matches Biome's formatting
// (tab indent, double quotes, trailing comma) and `biome ci` stays green.
const entries = Object.entries(redirects)
	.map(([from, to]) => `\t${JSON.stringify(from)}: ${JSON.stringify(to)},`)
	.join("\n");

fs.writeFileSync(
	path.join(dataDir, "redirects.mjs"),
	`// Generated by scripts/gen-redirects.mjs — do not edit by hand.\n` +
		`// Maps the old Hexo permalinks to the new Astro post URLs.\n` +
		`export const redirects = {\n${entries}\n};\n`,
);

fs.writeFileSync(
	path.join(projectRoot, "public/_redirects"),
	`${lines.join("\n")}\n`,
);

console.log(`生成 ${Object.keys(redirects).length} 条重定向`);
console.log(Object.entries(redirects)
	.map(([from, to]) => `  ${decodeURI(from)}  ->  ${to}`)
	.join("\n"));
if (missing.length > 0) {
	console.warn(`\n缺少 published 字段，已跳过：${missing.join(", ")}`);
}
